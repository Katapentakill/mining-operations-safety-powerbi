"""Generate sql/01_staging.sql from the CSV headers (staging mirrors the CSV files 1:1).

Usage: python scripts/generate_staging_ddl.py
Staging columns are text (varchar in a UTF-8 collation, see sql/00_database.sql) so that every row loads
with its accents intact; types are applied in the ETL.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

LONG_TEXT = {"NARRATIVE", "DIRECTIONS_TO_MINE"}


def header(path: Path) -> list[str]:
    with open(path, encoding="utf-8-sig", newline="") as f:
        return next(csv.reader(f))


def main() -> int:
    cfg = common.load_config()
    base = common.data_dir(cfg) / "csv"
    slug = cfg["company"]["slug"]
    tables = [(f"stg.{meta['csv'][:-4]}", base / slug / meta["csv"]) for meta in common.TABLES.values()]
    tables += [
        ("stg.cu_price_monthly", base / "chile_context" / "cu_price_monthly.csv"),
        ("stg.cu_production_monthly", base / "chile_context" / "cu_production_monthly.csv"),
    ]
    out = [
        "-- GENERATED by scripts/generate_staging_ddl.py from the CSV headers. Do not edit by hand.",
        "USE MiningOpsSafety;",
        "GO",
        "",
    ]
    for name, path in tables:
        cols = header(path)
        out.append(f"DROP TABLE IF EXISTS {name};")
        out.append(f"CREATE TABLE {name} (")
        out.append(
            ",\n".join(f"    [{c}] {'varchar(max)' if c in LONG_TEXT else 'varchar(500)'} NULL" for c in cols)
        )
        out += [");", "GO", ""]
    target = common.ROOT / "sql" / "01_staging.sql"
    target.parent.mkdir(exist_ok=True)
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"escrito {target} ({len(tables)} tablas)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
