"""Profile the filtered MSHA CSV tables and write docs/data_profile.md.

Usage: python scripts/profile_data.py data/csv/freeport docs/data_profile.md
The report drives the data-model decisions (keys, grains, nulls, reconciliations).
"""
import sys
from pathlib import Path

import pandas as pd

CSV_DIR = Path(sys.argv[1])
OUT = Path(sys.argv[2])
NAMES = [
    "mines", "accidents", "inspections", "violations", "assessed_violations",
    "mines_prod_yearly", "mines_prod_quarterly", "controller_operator_history",
]
T = {n: pd.read_csv(CSV_DIR / f"{n}.csv", dtype=str, keep_default_na=False, encoding="utf-8-sig") for n in NAMES}
L: list[str] = []


def h(title):
    L.append(f"\n## {title}\n")


def md(head, rows):
    L.append("| " + " | ".join(head) + " |")
    L.append("|" + "---|" * len(head))
    for r in rows:
        L.append("| " + " | ".join(str(x) for x in r) + " |")
    L.append("")


def num(s):
    return pd.to_numeric(s.where(s != "", None), errors="coerce")


def dates(s):
    return pd.to_datetime(s.where(s != "", None), format="%m/%d/%Y", errors="coerce")


L.append("# Data profile\n")
L.append("Generated by `scripts/profile_data.py` from the filtered CSV snapshot. Do not edit by hand.")

# 1. rows and columns
h("1. Rows and columns")
md(["table", "rows", "columns"], [(n, f"{len(T[n]):,}", len(T[n].columns)) for n in NAMES])

# 2. candidate keys
h("2. Candidate keys (duplicates = rows beyond the first for the same key)")
KEYS = [
    ("mines", ["MINE_ID"]),
    ("accidents", ["DOCUMENT_NO"]),
    ("inspections", ["EVENT_NO"]),
    ("violations", ["EVENT_NO", "VIOLATION_NO"]),
    ("violations", ["VIOLATION_NO"]),
    ("assessed_violations", ["EVENT_NBR", "VIOLATION_NO"]),
    ("assessed_violations", ["VIOLATION_NO"]),
    ("mines_prod_yearly", ["MINE_ID", "SUBUNIT_CD", "CALENDAR_YR"]),
    ("mines_prod_quarterly", ["MINE_ID", "SUBUNIT_CD", "CAL_YR", "CAL_QTR"]),
    ("controller_operator_history", ["MINE_ID", "CONTROLLER_ID", "OPERATOR_ID", "OPERATOR_START_DT"]),
]
rows = []
for n, cols in KEYS:
    df = T[n]
    empty = int((df[cols] == "").any(axis=1).sum())
    dup = len(df) - len(df.drop_duplicates(subset=cols))
    rows.append((n, ", ".join(cols), f"{dup:,}", f"{empty:,}"))
md(["table", "key", "duplicates", "rows with empty key part"], rows)

# 3. orphans
h("3. Mines referenced by fact tables but missing in `mines`")
mine_ids = set(T["mines"]["MINE_ID"])
rows = []
for n in ["accidents", "inspections", "violations", "assessed_violations", "mines_prod_yearly", "mines_prod_quarterly", "controller_operator_history"]:
    miss = int((~T[n]["MINE_ID"].isin(mine_ids)).sum())
    rows.append((n, f"{miss:,}"))
md(["table", "orphan rows"], rows)

# 4. violations vs assessed
h("4. `violations` vs `assessed_violations`")
va = T["violations"][["EVENT_NO", "VIOLATION_NO"]].drop_duplicates()
aa = T["assessed_violations"][["EVENT_NBR", "VIOLATION_NO"]].drop_duplicates().rename(columns={"EVENT_NBR": "EVENT_NO"})
m = va.merge(aa, on=["EVENT_NO", "VIOLATION_NO"], how="outer", indicator=True)
vc = m["_merge"].value_counts()
md(["match on (EVENT_NO, VIOLATION_NO)", "rows"], [(k, f"{int(vc.get(k, 0)):,}") for k in ["both", "left_only", "right_only"]])
per = T["assessed_violations"].groupby(["EVENT_NBR", "VIOLATION_NO"]).size().value_counts().sort_index()
md(["assessed rows per violation", "violations"], [(int(k), f"{int(v):,}") for k, v in per.items()])
v = T["violations"]
a = T["assessed_violations"]
md(
    ["amount", "violations table", "assessed table"],
    [
        ("proposed penalty", f"{num(v['PROPOSED_PENALTY']).sum():,.0f}", f"{num(a['PROPOSED_PENALTY_AMT']).sum():,.0f}"),
        ("paid", f"{num(v['AMOUNT_PAID']).sum():,.0f}", f"{num(a['PAID_PROPOSED_PENALTY_AMT']).sum():,.0f}"),
        ("current assessment", "-", f"{num(a['CURRENT_ASSESSMENT_AMT']).sum():,.0f}"),
    ],
)

# 5. dates
h("5. Date columns (`mm/dd/yyyy`)")
DATECOLS = {
    "accidents": ["ACCIDENT_DT", "RETURN_TO_WORK_DT", "INVEST_BEGIN_DT"],
    "inspections": ["INSPECTION_BEGIN_DT", "INSPECTION_END_DT"],
    "violations": ["VIOLATION_ISSUE_DT", "VIOLATION_OCCUR_DT", "TERMINATION_DT"],
    "assessed_violations": ["ISSUE_DT", "OCCURRENCE_DT", "FINAL_ORDER_DT"],
    "mines": ["CURRENT_STATUS_DT"],
    "controller_operator_history": ["CONTROLLER_START_DT", "CONTROLLER_END_DT", "OPERATOR_START_DT", "OPERATOR_END_DT"],
}
rows = []
for n, cols in DATECOLS.items():
    for c in cols:
        s = T[n][c]
        filled = int((s != "").sum())
        d = dates(s)
        ok = int(d.notna().sum())
        rows.append((n, c, f"{filled:,}", f"{filled - ok:,}", d.min().date() if ok else "-", d.max().date() if ok else "-"))
md(["table", "column", "filled", "unparseable", "min", "max"], rows)

# 6. mostly-empty columns
h("6. Columns at least 90% empty (candidates to drop)")
rows = []
for n in NAMES:
    df = T[n]
    pct = (df == "").mean()
    cols = [f"{c} ({p:.0%})" for c, p in pct.items() if p >= 0.9]
    rows.append((n, ", ".join(cols) if cols else "-"))
md(["table", "columns"], rows)

# 7. accidents
h("7. Accidents")
ac = T["accidents"]
ctrl = ac["CONTROLLER_ID"]
md(
    ["check", "rows"],
    [
        ("controller at event = 0067299 (Freeport)", f"{int((ctrl == '0067299').sum()):,}"),
        ("controller at event empty", f"{int((ctrl == '').sum()):,}"),
        ("controller at event = another company", f"{int(((ctrl != '0067299') & (ctrl != '')).sum()):,}"),
        ("with contractor involved (CONTRACTOR_ID filled)", f"{int((ac['CONTRACTOR_ID'] != '').sum()):,}"),
        ("NO_INJURIES = 0", f"{int((num(ac['NO_INJURIES']) == 0).sum()):,}"),
        ("sum of NO_INJURIES", f"{num(ac['NO_INJURIES']).sum():,.0f}"),
        ("sum of DAYS_LOST", f"{num(ac['DAYS_LOST']).sum():,.0f}"),
    ],
)
top = ac[(ctrl != "0067299") & (ctrl != "")]["CONTROLLER_NAME"].value_counts().head(5)
md(["other controllers at event time", "accidents"], [(k, f"{v:,}") for k, v in top.items()])
md(["DEGREE_INJURY", "accidents"], [(k, f"{v:,}") for k, v in ac["DEGREE_INJURY"].value_counts().items()])
md(["SUBUNIT", "accidents"], [(k, f"{v:,}") for k, v in ac["SUBUNIT"].value_counts().items()])
md(["year", "accidents"], [(k, f"{v:,}") for k, v in ac["CAL_YR"].value_counts().sort_index().items()])

# 8. workforce reconciliation
h("8. Workforce: quarterly vs yearly hours")
q = T["mines_prod_quarterly"].copy()
y = T["mines_prod_yearly"].copy()
q["h"] = num(q["HOURS_WORKED"])
y["h"] = num(y["ANNUAL_HRS"])
qs = q.groupby(["MINE_ID", "SUBUNIT_CD", "CAL_YR"])["h"].sum().rename("q_hours")
ys = y.groupby(["MINE_ID", "SUBUNIT_CD", "CALENDAR_YR"])["h"].sum().rename("y_hours")
ys.index = ys.index.set_names(["MINE_ID", "SUBUNIT_CD", "CAL_YR"])
r = pd.concat([qs, ys], axis=1)
both = r.dropna()
diff = (both["q_hours"] - both["y_hours"]).abs()
md(
    ["check", "value"],
    [
        ("mine x area x year groups", f"{len(r):,}"),
        ("present in both tables", f"{len(both):,}"),
        ("only in quarterly", f"{int(r['y_hours'].isna().sum()):,}"),
        ("only in yearly", f"{int(r['q_hours'].isna().sum()):,}"),
        ("groups where hours differ", f"{int((diff > 0).sum()):,}"),
        ("max absolute difference (hours)", f"{diff.max():,.0f}"),
        ("total hours quarterly (matched groups)", f"{both['q_hours'].sum():,.0f}"),
        ("total hours yearly (matched groups)", f"{both['y_hours'].sum():,.0f}"),
    ],
)
last = q[q["CAL_YR"] == q["CAL_YR"].max()]
md(["latest year in quarterly", "quarters present"], [(q["CAL_YR"].max(), ", ".join(sorted(last["CAL_QTR"].unique())))])
md(["production columns", "non-empty rows"], [("ANNUAL_COAL_PROD (yearly)", int((y["ANNUAL_COAL_PROD"] != "").sum())), ("COAL_PRODUCTION (quarterly)", int((q["COAL_PRODUCTION"] != "").sum()))])

# 9. mines
h("9. Mines")
mn = T["mines"]
md(["status", "mines"], [(k, v) for k, v in mn["CURRENT_MINE_STATUS"].value_counts().items()])
md(["state", "mines"], [(k, v) for k, v in mn["STATE"].value_counts().items()])
md(["primary SIC", "mines"], [(k, v) for k, v in mn["PRIMARY_SIC"].value_counts().items()])
md(
    ["check", "mines"],
    [
        ("with latitude and longitude", int(((mn["LATITUDE"] != "") & (mn["LONGITUDE"] != "")).sum())),
        ("with NO_EMPLOYEES filled", int((mn["NO_EMPLOYEES"] != "").sum())),
    ],
)

# 10. violations / inspections
h("10. Violations and inspections")
vv = T["violations"]
md(["SIG_SUB", "violations"], [(k or "(empty)", f"{n:,}") for k, n in vv["SIG_SUB"].value_counts().items()])
md(["NEGLIGENCE", "violations"], [(k or "(empty)", f"{n:,}") for k, n in vv["NEGLIGENCE"].value_counts().head(8).items()])
ins = T["inspections"]
md(
    ["inspections check", "value"],
    [
        ("TOTAL_INSP_HOURS filled", f"{int((ins['TOTAL_INSP_HOURS'] != '').sum()):,}"),
        ("sum TOTAL_INSP_HOURS", f"{num(ins['TOTAL_INSP_HOURS']).sum():,.0f}"),
        ("sum TOTAL_ON_SITE_HOURS", f"{num(ins['TOTAL_ON_SITE_HOURS']).sum():,.0f}"),
    ],
)

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"escrito {OUT} ({len(L)} lineas)")
